"""Build and execute BluePearlCLI runs, then collect their results."""

from __future__ import annotations

import asyncio
import json
import os
import re
import time
import uuid
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Awaitable, Callable

from .config import Settings
from .parsers import Message, parse_csv, parse_log, parse_sarif

ProgressCb = Callable[[float, str], Awaitable[None]]

_MARK = "BPMCP"  # prefix for lines the wrapper Tcl prints, so we can find them in stdout


def tcl_quote(value: str | Path) -> str:
    """Quote a value for Tcl using braces. Paths use forward slashes (works on Windows too)."""
    s = value.as_posix() if isinstance(value, Path) else str(value)
    if any(c in s for c in "{}\\\n\r") or s.count("{") != s.count("}"):
        raise ValueError(f"Unsupported character in Tcl value: {s!r}")
    return "{" + s + "}"


_NAME_RE = re.compile(r"^[A-Za-z0-9_ .:\-/()&+']+$")


def _safe_name(kind: str, value: str) -> str:
    if not _NAME_RE.match(value):
        raise ValueError(f"Invalid {kind} name: {value!r}")
    return value


@dataclass
class RunSpec:
    ffile: Path | None = None
    hdl_files: list[Path] = field(default_factory=list)
    # Files added in Tcl with an explicit language, e.g. (path, "VHDL_2008") or (path, "SYS_VERILOG").
    typed_files: list[tuple[Path, str]] = field(default_factory=list)
    include_dirs: list[Path] = field(default_factory=list)
    defines: dict[str, str] = field(default_factory=dict)
    top: str | None = None
    setup_tcl: list[Path] = field(default_factory=list)
    waivers: Path | None = None
    packages: list[str] = field(default_factory=list)
    enable_checks: list[str] = field(default_factory=list)
    disable_checks: list[str] = field(default_factory=list)
    phase: str = "analyze"  # "load", "analyze" or "none" (setup Tcl already calls BPS::run)
    timeout_s: int | None = None
    extra_args: list[str] = field(default_factory=list)


@dataclass
class RunRecord:
    run_id: str
    run_dir: str
    command: list[str]
    started: float
    duration_s: float = 0.0
    returncode: int | None = None
    timed_out: bool = False
    output_dir: str | None = None
    log_path: str | None = None
    sarif_path: str | None = None
    csv_path: str | None = None
    parsed_from: str | None = None
    notes: list[str] = field(default_factory=list)
    stdout_tail: str = ""
    messages: list[Message] = field(default_factory=list)

    def meta(self) -> dict:
        d = asdict(self)
        d.pop("messages")
        return d

    def save(self) -> None:
        rd = Path(self.run_dir)
        (rd / "run.json").write_text(json.dumps(self.meta(), indent=2))
        (rd / "messages.json").write_text(json.dumps([asdict(m) for m in self.messages]))

    @classmethod
    def load(cls, run_dir: Path) -> "RunRecord":
        meta = json.loads((run_dir / "run.json").read_text())
        msgs_file = run_dir / "messages.json"
        msgs = [Message(**m) for m in json.loads(msgs_file.read_text())] if msgs_file.exists() else []
        return cls(**meta, messages=msgs)


def new_run_dir(settings: Settings, label: str = "run") -> tuple[str, Path]:
    run_id = time.strftime("%Y%m%d-%H%M%S") + "-" + uuid.uuid4().hex[:6]
    run_dir = settings.runs_dir / f"{label}-{run_id}"
    run_dir.mkdir(parents=True, exist_ok=False)
    return run_id, run_dir


def build_wrapper_tcl(spec: RunSpec, csv_path: Path) -> str:
    lines = ["# Generated by bluepearl-mcp", "set bpmcp_status 0"]
    for path, lang in spec.typed_files:
        lines.append(f"BPS::add_input_files -language {_safe_name('language', lang)} {tcl_quote(path)}")
    for pkg in spec.packages:
        lines.append(f"BPS::set_package_enabled {tcl_quote(_safe_name('package', pkg))} -enabled true")
    for chk in spec.enable_checks:
        lines.append(f"BPS::set_check_enabled {tcl_quote(_safe_name('check', chk))} -enabled true")
    for chk in spec.disable_checks:
        lines.append(f"BPS::set_check_enabled {tcl_quote(_safe_name('check', chk))} -enabled false")

    phases = {"load": ["load"], "analyze": ["load", "analyze"], "none": []}[spec.phase]
    for ph in phases:
        lines += [
            f'puts "{_MARK}-PHASE: {ph}"',
            f"if {{[catch {{BPS::run {ph}}} bpmcp_err]}} {{",
            f'    puts "{_MARK}-ERROR: BPS::run {ph} failed: $bpmcp_err"',
            "    set bpmcp_status 1",
            "}",
        ]
    lines += [
        f'catch {{puts "{_MARK}-OUTPUTDIR: [BPS::get_outputdir]"}}',
        f"if {{[catch {{BPS::get_result_run_messages -reportcsv {tcl_quote(csv_path)}}} bpmcp_err]}} {{",
        f'    puts "{_MARK}-WARN: CSV export failed: $bpmcp_err"',
        "}",
        "exit $bpmcp_status",
        "",
    ]
    return "\n".join(lines)


def build_command(settings: Settings, spec: RunSpec, run_dir: Path, wrapper: Path) -> list[str]:
    if not settings.cli:
        raise RuntimeError(
            "BluePearlCLI not found. Set BLUEPEARL_CLI to the executable or BLUEPEARL_HOME to the install directory."
        )
    cmd = [settings.cli, *settings.extra_cli_args]
    # -f first: a GUI-generated .f may itself set -output/-waivers; ours come after so they take effect.
    if spec.ffile:
        cmd += ["-f", str(spec.ffile)]
    cmd += [
        "-output", str(run_dir / "results"),
        "-logfile", str(run_dir / "bluepearl.log"),
        "-write_sarif",
        "-verbosity", "2",
    ]
    if spec.waivers:
        cmd += ["-waivers", str(spec.waivers)]
    if spec.top:
        cmd += ["-root", _safe_name("top module", spec.top)]
    for d in spec.include_dirs:
        cmd.append(f"+incdir+{d}")
    for k, v in spec.defines.items():
        _safe_name("define", k)
        cmd.append(f"+define+{k}={v}" if v != "" else f"+define+{k}")
    cmd += spec.extra_args
    cmd += [str(f) for f in spec.hdl_files]
    for t in spec.setup_tcl:
        cmd += ["-tcl", str(t)]
    cmd += ["-tcl", str(wrapper)]
    return cmd


async def _run_process(
    cmd: list[str], cwd: Path, stdout_file: Path, timeout_s: int, progress: ProgressCb | None
) -> tuple[int | None, bool]:
    with stdout_file.open("wb") as out:
        proc = await asyncio.create_subprocess_exec(
            *cmd, cwd=str(cwd), stdout=out, stderr=asyncio.subprocess.STDOUT, stdin=asyncio.subprocess.DEVNULL
        )
        start = time.monotonic()
        while True:
            try:
                await asyncio.wait_for(proc.wait(), timeout=5)
                return proc.returncode, False
            except asyncio.TimeoutError:
                elapsed = time.monotonic() - start
                if elapsed > timeout_s:
                    proc.kill()
                    await proc.wait()
                    return proc.returncode, True
                if progress:
                    phase = _last_phase(stdout_file)
                    await progress(elapsed, f"Blue Pearl running ({phase or 'starting'}), {int(elapsed)}s elapsed")


def _last_phase(stdout_file: Path) -> str | None:
    try:
        tail = stdout_file.read_bytes()[-20000:].decode("utf-8", "replace")
    except OSError:
        return None
    phases = re.findall(rf"{_MARK}-PHASE: (\w+)", tail)
    return phases[-1] if phases else None


def _tail(path: Path, n: int = 60) -> str:
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return ""
    return "\n".join(lines[-n:])


def _find_sarif(dirs: list[Path], since: float) -> Path | None:
    cands: list[Path] = []
    for d in dirs:
        if d and d.is_dir():
            cands += [p for p in d.rglob("*.sarif*") if p.is_file() and p.stat().st_mtime >= since - 1]
    return max(cands, key=lambda p: p.stat().st_mtime) if cands else None


def collect_results(rec: RunRecord, csv_path: Path, stdout_file: Path, extra_dirs: list[Path]) -> None:
    """Fill rec.messages from the best available source."""
    run_dir = Path(rec.run_dir)
    stdout = stdout_file.read_text(encoding="utf-8", errors="replace") if stdout_file.exists() else ""
    m = re.findall(rf"{_MARK}-OUTPUTDIR: (.+)", stdout)
    if m:
        rec.output_dir = m[-1].strip()
    rec.notes += [ln.strip() for ln in stdout.splitlines() if ln.startswith((f"{_MARK}-ERROR", f"{_MARK}-WARN"))]

    log = run_dir / "bluepearl.log"
    rec.log_path = str(log) if log.exists() else None
    dirs = [run_dir, *extra_dirs] + ([Path(rec.output_dir)] if rec.output_dir else [])
    sarif = _find_sarif(dirs, rec.started)

    attempts: list[tuple[str, Path | None, Callable[[Path], list[Message]]]] = [
        ("sarif", sarif, parse_sarif),
        ("csv", csv_path if csv_path.exists() else None, parse_csv),
        ("log", log if log.exists() else None, parse_log),
        ("stdout", stdout_file if stdout_file.exists() else None, parse_log),
    ]
    for name, path, fn in attempts:
        if not path:
            continue
        try:
            msgs = fn(path)
        except Exception as e:  # noqa: BLE001 - keep going with the next source
            rec.notes.append(f"Could not parse {name} ({path}): {e}")
            continue
        if name == "sarif":
            rec.sarif_path = str(path)
        if name == "csv":
            rec.csv_path = str(path)
        # Accept the first source that yields messages; an empty SARIF is also authoritative.
        if msgs or name == "sarif":
            rec.messages, rec.parsed_from = msgs, name
            break
    if rec.parsed_from is None:
        rec.notes.append("No result messages could be found in SARIF, CSV, log or stdout.")


async def execute(
    settings: Settings,
    spec: RunSpec,
    progress: ProgressCb | None = None,
    run: tuple[str, Path] | None = None,
) -> RunRecord:
    """Run Blue Pearl. `run` is an already-created (run_id, run_dir) from new_run_dir, if the caller
    needed to put files in the run directory first."""
    run_id, run_dir = run or new_run_dir(settings)
    csv_path = run_dir / "messages.csv"
    wrapper = run_dir / "bpmcp_run.tcl"
    wrapper.write_text(build_wrapper_tcl(spec, csv_path))
    cmd = build_command(settings, spec, run_dir, wrapper)
    rec = RunRecord(run_id=run_id, run_dir=str(run_dir), command=cmd, started=time.time())
    stdout_file = run_dir / "stdout.txt"
    t0 = time.monotonic()
    cwd = spec.ffile.parent if spec.ffile else run_dir  # .f files often use paths relative to themselves
    rec.returncode, rec.timed_out = await _run_process(
        cmd, cwd, stdout_file, spec.timeout_s or settings.default_timeout_s, progress
    )
    rec.duration_s = round(time.monotonic() - t0, 1)
    collect_results(rec, csv_path, stdout_file, [run_dir / "results"])
    if rec.timed_out:
        rec.notes.append(f"Run killed after {spec.timeout_s or settings.default_timeout_s}s timeout.")
    if rec.timed_out or rec.returncode not in (0, None) or not rec.messages:
        rec.stdout_tail = _tail(stdout_file)
    rec.save()
    return rec


async def run_cli_capture(settings: Settings, args: list[str], timeout_s: int = 120) -> tuple[int | None, str]:
    """Run BluePearlCLI for a short query (help, check listing) and return its output."""
    if not settings.cli:
        raise RuntimeError("BluePearlCLI not found. Set BLUEPEARL_CLI or BLUEPEARL_HOME.")
    settings.runs_dir.mkdir(parents=True, exist_ok=True)
    proc = await asyncio.create_subprocess_exec(
        settings.cli, *settings.extra_cli_args, *args,
        cwd=str(settings.runs_dir),
        stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.STDOUT, stdin=asyncio.subprocess.DEVNULL,
        env=os.environ.copy(),
    )
    try:
        out, _ = await asyncio.wait_for(proc.communicate(), timeout=timeout_s)
    except asyncio.TimeoutError:
        proc.kill()
        await proc.wait()
        return None, "Timed out."
    return proc.returncode, out.decode("utf-8", "replace")


async def import_results(settings: Settings, path: Path, result_id: int | None = None) -> RunRecord:
    """Load messages from an existing SARIF/CSV/log file or a Blue Pearl results directory."""
    run_id, run_dir = new_run_dir(settings, label="import")
    rec = RunRecord(run_id=run_id, run_dir=str(run_dir), command=[], started=0.0)
    if path.is_file():
        suffix = path.suffix.lower()
        fn, name = (
            (parse_sarif, "sarif") if suffix in (".sarif", ".json")
            else (parse_csv, "csv") if suffix == ".csv"
            else (parse_log, "log")
        )
        rec.messages, rec.parsed_from = fn(path), name
        rec.log_path = str(path) if name == "log" else None
        rec.sarif_path = str(path) if name == "sarif" else None
        rec.csv_path = str(path) if name == "csv" else None
    else:
        sarif = _find_sarif([path], since=0)
        if sarif and result_id is None:
            rec.messages, rec.parsed_from, rec.sarif_path = parse_sarif(sarif), "sarif", str(sarif)
        else:
            # Ask Blue Pearl to export a result run from the results.db in that directory.
            csv_path = run_dir / "messages.csv"
            rid = f" -resultid {int(result_id)}" if result_id is not None else ""
            args = [
                "-output", str(path),
                "-e", f"BPS::get_result_run_messages{rid} -reportcsv {tcl_quote(csv_path)}",
                "-e", "exit",
            ]
            rec.command = [settings.cli or "BluePearlCLI", *args]
            rc, out = await run_cli_capture(settings, args, timeout_s=600)
            rec.returncode = rc
            if csv_path.exists():
                rec.messages, rec.parsed_from, rec.csv_path = parse_csv(csv_path), "csv", str(csv_path)
            else:
                rec.notes.append("Export from results.db produced no CSV.")
                rec.stdout_tail = "\n".join(out.splitlines()[-60:])
    rec.output_dir = str(path if path.is_dir() else path.parent)
    rec.save()
    return rec
